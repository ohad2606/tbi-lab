/**
 * TBI-018 slice 3c: SimHostAdapter, the thin layer between the Session Host and SimMeter + FairQueue.
 * NOT WIRED: the Session Host refuses to start with an enabled adapter until the host slice lands
 * (runtime/host/host.ts, see docs/runtime/TBI-018-sim-host-integration.md). metering.enabled=false (the
 * default) makes every call answer { metered: false } and do nothing, so the host behaves as today.
 *
 * The host calls, in order:
 *   admit(req)          at session open, and again on every poll of a queued client (same ticket).
 *                       start   = the meter opened the session (plan FIXED here, for the whole run);
 *                       queued  = wait, poll again; refused = explicit LimitError, nothing opened.
 *   heartbeat(id, principal)  while the run lives (and when remainingMs elapses). continue = keep running,
 *                       arm a stop timer at remainingMs; stop = end the run now with the error;
 *                       refused = the caller does not own this run: answer the caller with the error
 *                       and DO NOT touch the run (it is someone else's).
 *                       Billing is capped at the heartbeat that detected 0 (overshoot <= one interval).
 *   ended(id, reason, principal)  once the host session is terminal: bills (idempotent), starts the Free cooldown.
 *                       The principal is REQUIRED (LOW5): it must be the one recorded at admission (and
 *                       in the meter session); a missing one is invalid_request, another one invalid_state,
 *                       and neither ends, bills or untracks the run.
 *   housekeeping()      on the host timer: drops timed-out / vanished waiters, bills lease-lost runs and
 *                       stops tracking runs whose meter session is closed or whose lease ran out (a missed
 *                       ended() must not hold a slot or the Free cap forever; the Free cooldown starts then).
 *   cancel / touch      (ticket, principal) for a waiting client; act only on that principal's own entry.
 *
 * HOST CONTRACT (s3b follow-up 12, ops review fable11 M1): the host MUST pass the authenticated principal
 * of the CALLER on heartbeat() and ended() (it is optional only for the pure layer's old callers). A run
 * owned by another principal changes nothing: heartbeat answers decision 'refused' (invalid_state), never
 * 'stop', so a foreign caller can never make the host stop another user's run; ended() answers ok:false.
 * The host answers such a caller with the same invalid_state error as for an unknown id (nothing
 * revealed). Without the principal the session id alone is the capability, so it must stay unguessable
 * and never leave the server.
 *
 * Tickets must be generated by the server (unguessable, never taken from the client as an identity); even
 * so every ticket operation checks that the queued entry belongs to the calling principal.
 *
 * Fairness: every request goes through the queue, so a newcomer never jumps a waiting entry; it starts
 * only when it is the first eligible entry and a slot is free. A direct start therefore also obeys the
 * Free cooldown (enqueue checks FairQueue.cooldownMs; s3b follow-up). Free slot cap counts plan 'free' only; legacy is
 * ranked with Advanced and is not under the Free cap (owner decision 2026-11-22).
 * Running count: the larger of the host's count and the sessions this adapter admitted and the host has
 * not reported ended (the host's picture may lag a concurrent admit). One serial mutex.
 * Fail closed: any meter problem refuses (admit) or stops (heartbeat) with system_unavailable.
 *
 * BETA-G2 kill switch (optional `freePaused` probe, absent = never paused): while it answers anything but
 * `false` (a throw counts as paused, fail closed) every NEW Free admission and every Free poll is refused
 * with free_paused, and waiting Free entries are dropped (at any admit and at housekeeping). Running runs
 * are never stopped by it; paid / legacy admissions are unaffected. Checked on every call: no restart.
 */
import type { PlanId, PlansConfig } from './config.js';
import { PLAN_IDS } from './config.js';
import { limitError, validPrincipal, type LimitError } from './limits.js';
import { FairQueue, type Dropped } from './queue.js';
import { SimMeter, type CloseReason, type SimEvent } from './simminutes.js';
import type { Store, StoreProblem } from './store.js';
import type { Clock } from './time.js';

/** The host's slot picture at the moment of the call. The capacity is the host's, never assumed. */
export interface HostSlots {
  capacity: number;
  running: number;
  /** queue.freeCapMode = liftUntilFirstPaid only */
  anyPaidUser?: boolean;
}

export interface HostAdmitRequest {
  /** opaque id of the waiting request; the client sends it again on each poll */
  ticket: string;
  /** the host session id the run will have */
  sessionId: string;
  principal: string;
  /** the plan resolved by the host at this moment; fixed for the run once it starts */
  plan: PlanId;
  slots: HostSlots;
  /**
   * TBI-018 s3d-3b (design sections 3 and 4). Absent = 'join' (the s3c behaviour, unchanged).
   *   join    a new admission: the ticket joins the queue (or takes over the principal's entry);
   *   poll    the ticket must already wait for this principal: when it does not (dropped by max wait or
   *           as vanished, cancelled, or never queued), the answer is refused with that drop's error
   *           (queue_timeout when unknown) and NOTHING is enqueued, so a poll never restarts the wait;
   *   legacy  a client without the queue protocol: it never creates, replaces or cancels an entry.
   *           When the principal already has an entry the answer is 'queued' and the entry is left
   *           alone; a 'queued' outcome of its own is removed in the same serial step (never visible
   *           to another caller). Only a 'start' or a refusal has an effect.
   */
  mode?: 'join' | 'poll' | 'legacy';
}

type Off = { metered: false };
const OFF: Off = { metered: false };

export type HostAdmit =
  | Off
  | {
      metered: true;
      decision: 'start';
      sessionId: string;
      plan: PlanId;
      /** ms left (smaller of month and day); null = no sim limit for this plan */
      remainingMs: number | null;
      dropped: Dropped[];
    }
  | { metered: true; decision: 'queued'; position: number; status: LimitError; dropped: Dropped[] }
  | { metered: true; decision: 'refused'; error: LimitError; dropped: Dropped[] };

export type HostBeat =
  | Off
  | { metered: true; decision: 'continue'; remainingMs: number | null }
  | { metered: true; decision: 'stop'; error: LimitError }
  /** the caller is not the run's principal: nothing changed; the host must NOT stop the run */
  | { metered: true; decision: 'refused'; error: LimitError };

export type HostEnd =
  | Off
  | { metered: true; ok: true; billedMs: number }
  | { metered: true; ok: false; error: LimitError };

export type HostHousekeeping =
  | Off
  /** closed = runs the sweep billed; pruned = runs no longer tracked as running (missed ended()) */
  | { metered: true; ok: true; closed: number; pruned: number; dropped: Dropped[] }
  | { metered: true; ok: false; error: LimitError; dropped: Dropped[] };

/** Host end reason -> meter close reason. Billing is the same formula for all of them. */
export function closeReasonOf(hostReason: string): CloseReason {
  if (hostReason === 'lease_expired') return 'lease';
  if (hostReason === 'host_shutdown') return 'host';
  return 'ended';
}

const minLeft = (r: { monthMs: number | null; dayMs: number | null }): number | null => {
  const left = [r.monthMs, r.dayMs].filter((x): x is number => x !== null);
  return left.length ? Math.min(...left) : null;
};

export interface SimHostOptions {
  config: PlansConfig;
  clock: Clock;
  /** BETA-G2: operator kill switch for new Free admissions; true (or a throw) = paused */
  freePaused?: () => boolean;
}

export class SimHostAdapter {
  private readonly live = new Map<string, { principal: string; plan: PlanId }>();
  private tail: Promise<unknown> = Promise.resolve();

  private constructor(
    private readonly meter: SimMeter,
    private readonly queue: FairQueue,
    private readonly cfg: PlansConfig,
    private readonly clock: Clock,
    private readonly freePausedProbe?: () => boolean,
  ) {}

  static async open(store: Store<SimEvent>, opts: SimHostOptions): Promise<SimHostAdapter> {
    const meter = await SimMeter.open(store, opts);
    return new SimHostAdapter(
      meter,
      new FairQueue(opts.config, opts.clock),
      opts.config,
      opts.clock,
      opts.freePaused,
    );
  }

  /** BETA-G2: is the Free kill switch on? Only an explicit `false` means no; a probe failure means yes. */
  get freePaused(): boolean {
    const probe = this.freePausedProbe;
    if (!probe) return false;
    try {
      return probe() !== false;
    } catch {
      return true;
    }
  }

  get enabled(): boolean {
    return this.cfg.metering.enabled;
  }
  /** the meter's journal problem, if any (read-only; s3d-1: the host refuses to boot on one) */
  get storeProblem(): StoreProblem | undefined {
    return this.meter.storeProblem;
  }
  /** sessions admitted and not yet reported ended */
  get tracked(): number {
    return this.live.size;
  }
  get waiting(): number {
    return this.queue.length;
  }
  /** the plan a run was admitted with (fixed at open) */
  planOf(sessionId: string): PlanId | undefined {
    return this.live.get(sessionId)?.plan;
  }

  /**
   * TBI-018 s3d-6 boot recovery (design §7): close every meter session still open with reason 'host'
   * (SimMeter.closeAllOpen). Only before this process admitted anything: with a tracked run it refuses
   * (invalid_state) and closes nothing, so it can never end a run of this process.
   */
  recoverAtBoot(): Promise<
    | Off
    | { metered: true; ok: true; closed: number }
    | { metered: true; ok: false; error: LimitError }
  > {
    if (!this.enabled) return Promise.resolve(OFF);
    return this.run(async () => {
      if (this.live.size > 0)
        return { metered: true as const, ok: false as const, error: limitError('invalid_state') };
      const r = await this.meter.closeAllOpen('host');
      if (!r.ok) return { metered: true as const, ok: false as const, error: r.error };
      if (!r.metered)
        return { metered: true as const, ok: false as const, error: limitError('invalid_state') };
      return { metered: true as const, ok: true as const, closed: r.closed };
    });
  }

  /**
   * TBI-018 s3d-6 boot compaction (SimMeter.compact): only when no meter session is open and this
   * process tracks no run. `skipped` = nothing done (sessions open); the caller copies the journal first.
   */
  compactAtBoot(): Promise<
    | Off
    | { metered: true; ok: true; skipped: boolean }
    | { metered: true; ok: false; error: LimitError }
  > {
    if (!this.enabled) return Promise.resolve(OFF);
    return this.run(async () => {
      if (this.live.size > 0 || this.meter.openCount > 0)
        return { metered: true as const, ok: true as const, skipped: true };
      const r = await this.meter.compact();
      if (!r.ok) return { metered: true as const, ok: false as const, error: r.error };
      return { metered: true as const, ok: true as const, skipped: false };
    });
  }

  /** meter sessions not closed (journaled state) */
  get openMeterSessions(): number {
    return this.meter.openCount;
  }
  /** events in the journal since it began or was last compacted (boot compaction threshold) */
  get journalSeq(): number {
    return this.meter.journalSeq;
  }

  /** Is `ticket` queued, and is it `principal`'s entry? */
  private owns(ticket: string, principal: string): boolean {
    return this.queue.snapshot().some((e) => e.ticket === ticket && e.principal === principal);
  }

  private run<T>(fn: () => Promise<T>): Promise<T> {
    const p = this.tail.then(fn);
    this.tail = p.catch(() => undefined);
    return p;
  }

  admit(req: HostAdmitRequest): Promise<HostAdmit> {
    if (!this.enabled) return Promise.resolve(OFF);
    return this.run(async () => {
      const refuse = (error: LimitError, dropped: Dropped[] = []): HostAdmit => ({
        metered: true,
        decision: 'refused',
        error,
        dropped,
      });
      const s = req.slots;
      if (
        !s ||
        !Number.isSafeInteger(s.capacity) ||
        !Number.isSafeInteger(s.running) ||
        s.capacity < 0 ||
        s.running < 0 ||
        !PLAN_IDS.includes(req.plan)
      )
        return refuse(limitError('invalid_request'));
      const mode = req.mode ?? 'join';
      if (mode !== 'join' && mode !== 'poll' && mode !== 'legacy')
        return refuse(limitError('invalid_request'));
      if (this.live.has(req.sessionId)) return refuse(limitError('invalid_state'));
      if (this.meter.storeProblem) return refuse(limitError('system_unavailable'));
      const early: Dropped[] = [];
      // BETA-G2 kill switch: waiting Free entries go (also this caller's own), a Free caller is refused
      if (this.freePaused) {
        early.push(...this.queue.dropFree());
        if (req.plan === 'free') return refuse(limitError('free_paused'), early);
      }
      // s3d-3b poll: expire stale entries first (this poll is the principal's sign of life, as in
      // enqueue); a ticket that no longer waits is answered with its drop, never re-enqueued
      if (mode === 'poll') {
        early.push(...this.queue.tick(req.principal));
        if (!this.owns(req.ticket, req.principal)) {
          const own = early.find((d) => d.ticket === req.ticket && d.principal === req.principal);
          return refuse(own?.error ?? limitError('queue_timeout'), early);
        }
      }
      // s3d-3b legacy: an existing entry of this principal (another tab's place) is never touched
      if (mode === 'legacy') {
        early.push(...this.queue.tick());
        const theirs = this.queue.snapshot().findIndex((e) => e.principal === req.principal);
        if (theirs !== -1)
          return {
            metered: true,
            decision: 'queued',
            position: theirs + 1,
            status: limitError('queue', { n: theirs + 1 }),
            dropped: early,
          };
      }
      // s3b follow-up (host must apply the Free cooldown to direct starts): every start, also into an
      // idle slot, goes through enqueue, which refuses a new Free entry with sim_cooldown.
      const ok = this.meter.admissible(req.principal, req.plan);
      if (!ok.ok) {
        if (this.owns(req.ticket, req.principal)) this.queue.drop(req.ticket);
        return refuse(ok.error, early);
      }
      if (!ok.metered) return refuse(limitError('invalid_state'), early); // metering changed under us
      const used = this.meter.usedTodayMs(req.principal);
      if (!used.ok || !used.metered) return refuse(limitError('system_unavailable'), early);
      // no tick() of our own here: enqueue ticks with req.principal as alive, so this poll is the
      // waiter's sign of life and its entry is not dropped as vanished first (ops review fable11 L3)
      const q = this.queue.enqueue({
        ticket: req.ticket,
        principal: req.principal,
        plan: req.plan,
        simMsToday: used.ms,
      });
      const dropped: Dropped[] = [...early, ...(q.dropped ?? [])];
      if (!q.ok) return refuse(q.error, dropped);
      const running = Math.max(s.running, this.live.size);
      const runningFree = [...this.live.values()].filter((x) => x.plan === 'free').length;
      const slots = { capacity: s.capacity, running, runningFree, anyPaidUser: s.anyPaidUser };
      const queuedResult = (): HostAdmit => {
        const position = this.queue.position(req.ticket) as number;
        // s3d-3b legacy: its own entry never stays (same serial step, nobody else saw it)
        if (mode === 'legacy') this.queue.drop(req.ticket);
        return {
          metered: true,
          decision: 'queued',
          position,
          status: limitError('queue', { n: position }),
          dropped,
        };
      };
      if (running >= s.capacity) return queuedResult();
      // one atomic step (one clock reading): take our entry only if it is the first eligible one, so
      // another waiter is never removed on our behalf (L1)
      const out = this.queue.dequeue(slots, req.ticket);
      dropped.push(...out.dropped);
      if (!out.entry) {
        if (this.queue.position(req.ticket) !== null) return queuedResult();
        // our own entry was dropped by the dequeue's tick (max wait / vanished at this very moment)
        const own = out.dropped.find((d) => d.ticket === req.ticket);
        return refuse(own?.error ?? limitError('invalid_state'), dropped);
      }
      const opened = await this.meter.open(req.sessionId, req.principal, out.entry.plan);
      if (!opened.ok) return refuse(opened.error, dropped);
      if (!opened.metered) return refuse(limitError('invalid_state'), dropped);
      this.live.set(req.sessionId, { principal: req.principal, plan: out.entry.plan });
      return {
        metered: true,
        decision: 'start',
        sessionId: req.sessionId,
        plan: out.entry.plan,
        remainingMs: minLeft(opened),
        dropped,
      };
    });
  }

  heartbeat(sessionId: string, principal?: string): Promise<HostBeat> {
    if (!this.enabled) return Promise.resolve(OFF);
    return this.run(async () => {
      const live = this.live.get(sessionId);
      if (live && principal !== undefined && live.principal !== principal)
        return { metered: true, decision: 'refused', error: limitError('invalid_state') };
      if (!live) return { metered: true, decision: 'stop', error: limitError('invalid_state') };
      const r = await this.meter.heartbeat(sessionId, principal);
      if (!r.ok) return { metered: true, decision: 'stop', error: r.error };
      if (!r.metered)
        return { metered: true, decision: 'stop', error: limitError('invalid_state') };
      return { metered: true, decision: 'continue', remainingMs: r.remainingMs };
    });
  }

  /**
   * The host session is terminal. Bills it (a second call is a duplicate) and frees the slot. Only the
   * principal the run was admitted for may end it (LOW5): the adapter's record while it tracks the run,
   * the meter session's record after that (housekeeping may have stopped tracking it).
   */
  ended(sessionId: string, reason: CloseReason, principal: string): Promise<HostEnd> {
    if (!this.enabled) return Promise.resolve(OFF);
    return this.run(async () => {
      if (!validPrincipal(principal))
        return { metered: true, ok: false, error: limitError('invalid_request') };
      const s = this.live.get(sessionId);
      if (s && s.principal !== principal)
        return { metered: true, ok: false, error: limitError('invalid_state') };
      this.live.delete(sessionId);
      if (s) this.queue.sessionEnded(s.principal, s.plan);
      const r = await this.meter.close(sessionId, reason, principal);
      if (!r.ok) return { metered: true, ok: false, error: r.error };
      if (!r.metered) return { metered: true, ok: false, error: limitError('invalid_state') };
      return { metered: true, ok: true, billedMs: r.billedMs };
    });
  }

  housekeeping(): Promise<HostHousekeeping> {
    if (!this.enabled) return Promise.resolve(OFF);
    return this.run(async () => {
      const dropped = this.queue.tick();
      if (this.freePaused) dropped.push(...this.queue.dropFree());
      const r = await this.meter.sweep();
      // prune also when the sweep failed: a run whose lease ran out is dead either way
      const pruned = this.prune();
      if (!r.ok) return { metered: true, ok: false, error: r.error, dropped };
      if (!r.metered)
        return { metered: true, ok: false, error: limitError('invalid_state'), dropped };
      return { metered: true, ok: true, closed: r.closed, pruned, dropped };
    });
  }

  /**
   * Stop tracking runs the host did not report ended: the meter session is gone or closed, or its lease
   * ran out (the meter's own rule: now > lastBeat + leaseMs). Frees the slot and starts the Free
   * cooldown (from now). A later ended() for it is a duplicate close and touches neither.
   */
  private prune(): number {
    const now = this.clock.now();
    if (!Number.isFinite(now)) return 0; // no trustworthy time: keep counting them (fail closed)
    let n = 0;
    for (const [id, s] of [...this.live]) {
      const ss = this.meter.session(id);
      if (ss && ss.closedAt === undefined && now <= ss.lastBeat + ss.leaseMs) continue;
      this.live.delete(id);
      this.queue.sessionEnded(s.principal, s.plan);
      n++;
    }
    return n;
  }

  /** A waiting client of `principal` cancelled (or its lease was lost). Someone else's ticket: no-op. */
  cancel(ticket: string, principal: string): Off | { metered: true; cancelled: boolean } {
    if (!this.enabled) return OFF;
    if (!this.owns(ticket, principal)) return { metered: true, cancelled: false };
    return { metered: true, cancelled: this.queue.drop(ticket) !== null };
  }

  /**
   * TBI-018 s3d-3a: read-only peek, has `principal` a live waiting entry (FairQueue.hasWaiting)? Used for
   * legacy clients (no `Tbi-Queue: 1`), which must never create, replace or cancel an entry (M3).
   * Disabled metering: false (there is no queue). Synchronous and mutation-free, so it needs no mutex.
   */
  hasWaiting(principal: string): boolean {
    if (!this.enabled) return false;
    return this.queue.hasWaiting(principal);
  }

  /** A waiting client of `principal` is still there (between polls). Someone else's ticket: no-op. */
  touch(ticket: string, principal: string): Off | { metered: true; queued: boolean } {
    if (!this.enabled) return OFF;
    if (!this.owns(ticket, principal)) return { metered: true, queued: false };
    return { metered: true, queued: this.queue.touch(ticket) };
  }
}
